`timescale 1ns/1ps

`include "defines.vh"

module execution_unit_tb;

//------------------------------------------------------------
// Testbench Signals
//------------------------------------------------------------

reg clk;
reg rst;

reg reg_write;

reg init_write;
reg [4:0] init_addr;
reg [31:0] init_data;

reg [`INSTR_WIDTH-1:0] instruction;

wire [31:0] alu_result;
wire zero;

//------------------------------------------------------------
// DUT
//------------------------------------------------------------

execution_unit DUT
(
    .clk(clk),
    .rst(rst),

    .reg_write(reg_write),

    .init_write(init_write),
    .init_addr(init_addr),
    .init_data(init_data),

    .instruction(instruction),

    .alu_result(alu_result),
    .zero(zero)
);

//------------------------------------------------------------
// Clock Generation
//------------------------------------------------------------

always #5 clk = ~clk;

//------------------------------------------------------------
// Test Sequence
//------------------------------------------------------------

initial
begin

    //--------------------------------------------------------
    // Initial Values
    //--------------------------------------------------------

    clk = 0;

    rst = 1;

    reg_write = 0;

    init_write = 0;
    init_addr = 0;
    init_data = 0;

    instruction = 32'd0;

    //--------------------------------------------------------
    // Apply Reset
    //--------------------------------------------------------

    #20;

    rst = 0;

    //--------------------------------------------------------
    // Initialize Register R1 = 10
    //--------------------------------------------------------

    init_write = 1;
    init_addr  = 5'd1;
    init_data  = 32'd10;

    #10;

    //--------------------------------------------------------
    // Initialize Register R2 = 20
    //--------------------------------------------------------

    init_addr = 5'd2;
    init_data = 32'd20;

    #10;

    //--------------------------------------------------------
    // Stop Initialization
    //--------------------------------------------------------

    init_write = 0;

    #10;

    //--------------------------------------------------------
    // Apply Instruction
    //
    // ADD R3,R1,R2
    //--------------------------------------------------------

    instruction =
    {
        4'b0000,
        5'd3,
        5'd1,
        5'd2,
        13'd0
    };

    //--------------------------------------------------------
    // Enable Write Back
    //--------------------------------------------------------

    reg_write = 1;

    #20;

    reg_write = 0;

    //--------------------------------------------------------
    // Display Results
    //--------------------------------------------------------

    $display("---------------------------------------");
    $display("Instruction = %h", instruction);
    $display("ALU Result  = %d", alu_result);
    $display("Zero Flag   = %b", zero);
    $display("---------------------------------------");

    #20;

    $finish;

end

endmodule
